"""Experiment for planned item B1: does the WORDING of an aspect change the judge's verdicts on the same findings?

Stored runs Q3 and Q4 (judge-v2). For selected aspects, the exact (finding, aspect) pairs that were judged in the stored run are judged again,
with the aspect reworded; the findings, quotes and passages are identical. Real judge, no database writes, temp verdict cache.

Variants (written 2026-11-07 BEFORE the first run, not tuned afterwards):
  control  the original wording (shows that the judge reproduces the stored verdicts, i.e. the noise floor)
  effect   "How does quantizing LLMs to 4-bit precision affect X?"  ->  "What is reported about X of LLMs quantized to 4-bit precision?"
  list1    "What are the existing benchmarks / metrics for evaluating the reasoning ability of LLMs?" -> "Which benchmarks / metrics are used to evaluate ...?"
  list2    list1 without the "?" + " (each one that a source uses is an answer)?"

Labels of the aspects (from report 16, fixed before): A = answerable, U = planner invented / not asked.
  Q3 effect aspects: A = representation, computation, accuracy, performance, memory, speed, quality, robustness; U = diversity, security,
  interoperability (compatibility is unsure and left out of the rule).  Q4 list aspects: A (existing benchmarks, existing metrics).

Pass rule: a rewording is worth adopting if (a) over the A-labeled aspects the number of "yes" verdicts rises by at least 25% (and by at least
3 pairs) against the control, and (b) over the U-labeled aspects it rises by at most 1 pair in total, and (c) the control reproduces the stored
verdicts for at least 90% of the pairs.

Usage:  python tests/aspect_wording_experiment.py
Output: reports/aspect_wording_experiment.json and a printed table.
"""
