Q3 = "bf7055b3-a202-4ef6-b47c-9e99c7f7a118"
Q4 = "d76170ee-fc49-4d07-9c4f-a1446bf6ff0c"

# (query, sub-question index (1-based), aspect index (0-based)) -> (label, variant name, reworded aspect)
EFFECT = {
    (Q3, 2, 0): ("A", "the representation of LLMs at 4-bit precision"),
    (Q3, 2, 1): ("A", "the computation of LLMs at 4-bit precision"),
    (Q3, 2, 2): ("A", "the accuracy of LLMs at 4-bit precision"),
    (Q3, 2, 3): ("A", "the performance of LLMs at 4-bit precision"),
    (Q3, 3, 0): ("A", "the model size and memory usage of LLMs quantized to 4-bit precision"),
    (Q3, 3, 1): ("A", "the inference speed and latency of LLMs quantized to 4-bit precision"),
    (Q3, 3, 2): ("A", "the quality of the text generated by LLMs quantized to 4-bit precision"),
    (Q3, 3, 3): ("U", "the diversity of the text generated by LLMs quantized to 4-bit precision"),
    (Q3, 3, 4): ("A", "the robustness of LLMs quantized to 4-bit precision"),
    (Q3, 3, 5): ("U", "the security of LLMs quantized to 4-bit precision"),
    (Q3, 3, 6): ("?", "the compatibility of LLMs quantized to 4-bit precision"),
    (Q3, 3, 7): ("U", "the interoperability of LLMs quantized to 4-bit precision"),
}
LISTS = {
    (Q4, 3, 2): ("A", "Which benchmarks are used to evaluate the reasoning ability of LLMs?"),
    (Q4, 3, 3): ("A", "Which metrics are used to evaluate the reasoning ability of LLMs?"),
}


def h(claim: str) -> str:
    return hashlib.sha256(claim.encode()).hexdigest()[:16]


def source_text(sources, source_id, chunk_id):
    kind, obj = sources.get(source_id, (None, None))
    if kind == "paper":
        chunks = chunk_selector.build_chunks(obj)
        return chunks[chunk_id] if isinstance(chunk_id, int) and 0 <= chunk_id < len(chunks) else ""
    if kind == "web":
        return obj.get("snippet") or ""
    return ""


def pairs_of(rows, aspect_idx):
    """The stored (finding, aspect) pairs of one aspect: [(source_id, finding, stored final verdict, stored aspect text)]."""
    out = []
    for r in rows:
        for f in r.get("findings") or []:
            j = (f.get("judge") or {}).get(str(aspect_idx))
            if isinstance(j, dict) and j.get("final") in ("yes", "partial", "no"):
                out.append((str(r["source_id"]), f, j["final"], j.get("aspect")))
    return out


def judge(pairs, aspect_text, chunk_lookup):
    cands = []
    for i, (source_id, f, _, _) in enumerate(pairs):
        cands.append({"aspect_idx": 0, "aspect_text": aspect_text, "source_id": source_id, "claim": f["claim"], "quote": f["quote"],
                      "chunk_id": f.get("chunk_id"), "item_id": hashlib.sha256(f"{aspect_text}|{source_id}|{i}".encode()).hexdigest()[:16]})
    verdicts = ej.judge_candidates(ej.build_judge_items(cands, chunk_lookup))
    return [verdicts.get((0, c["source_id"], h(c["claim"])), {}).get("verdict", {}).get("final", "error") for c in cands]


def main() -> int:
    ej.JUDGE_CACHE_PATH = Path(tempfile.mkdtemp()) / "judge_cache.json"
    todo = {**{k: (v[0], "effect", f"What is reported about {v[1]}?") for k, v in EFFECT.items()},
            **{k: (v[0], "list", v[1]) for k, v in LISTS.items()}}
    cache_rows = {}
    out, match_total, match_same = [], 0, 0
    for (qid, sqi, aidx), (label, kind, reworded) in todo.items():
        if (qid, sqi) not in cache_rows:
            sq = sorted(supabase.table("sub_questions").select("*").eq("query_id", qid).execute().data, key=lambda r: r["created_at"])[sqi - 1]
            rows = at.latest_generation([d for d in supabase.table("digests").select("*").eq("sub_question_id", sq["id"]).execute().data])
            for r in rows:
                if isinstance(r.get("findings"), str):
                    r["findings"] = json.loads(r["findings"])
            sources = {str(p["id"]): ("paper", p) for p in db_service.get_papers_for_stage3(qid, sq["id"])}
            sources.update({str(w["id"]): ("web", w) for w in supabase.table("web_sources").select("*").eq("sub_question_id", sq["id"]).execute().data})
            lookup = {}
            for r in rows:
                for f in r.get("findings") or []:
                    cid = f.get("chunk_id")
                    if isinstance(cid, int):
                        lookup[f"{r['source_id']}:{cid}"] = source_text(sources, str(r["source_id"]), cid)
            cache_rows[(qid, sqi)] = (rows, lookup)
        rows, lookup = cache_rows[(qid, sqi)]
        pairs = pairs_of(rows, aidx)
        original = pairs[0][3] if pairs else ""
        variants = {"control": [judge(pairs, original, lookup)]}
        if kind == "effect":
            variants["effect"] = [judge(pairs, reworded, lookup)]
        else:
            variants["list1"] = [judge(pairs, reworded, lookup)]
            variants["list2"] = [judge(pairs, reworded[:-1] + " (each one that a source uses is an answer)?", lookup)]
        stored = [p[2] for p in pairs]
        ctrl = variants["control"][0]
        match_total += len(stored)
        match_same += sum(1 for a, b in zip(stored, ctrl) if a == b)
        row = {"query": qid[:6], "sub_question": sqi, "aspect_idx": aidx, "label": label, "aspect": original, "pairs": len(pairs),
               "stored": dict(Counter(stored)), **{k: dict(Counter(v[0])) for k, v in variants.items()}}
        out.append(row)
        print(f"[{label}] {qid[:6]} s{sqi}#{aidx + 1} {original[:62]:62s} n={len(pairs)} stored {dict(Counter(stored))}  control {dict(Counter(ctrl))}  " +
              "  ".join(f"{k} {dict(Counter(v[0]))}" for k, v in variants.items() if k != "control"))
    (ROOT / "reports" / "aspect_wording_experiment.json").write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")

    def yes(row, key):
        return row.get(key, {}).get("yes", 0)
    print(f"\ncontrol reproduces the stored verdict for {match_same} of {match_total} pairs ({match_same / max(match_total, 1):.0%})")
    for key, kinds in (("effect", "Q3 effect aspects"), ("list1", "Q4 list aspects"), ("list2", "Q4 list aspects")):
        rel = [r for r in out if key in r]
        a = [r for r in rel if r["label"] == "A"]
        u = [r for r in rel if r["label"] == "U"]
        ya0, ya1 = sum(yes(r, "control") for r in a), sum(yes(r, key) for r in a)
        yu0, yu1 = sum(yes(r, "control") for r in u), sum(yes(r, key) for r in u)
        print(f"{key:7s} ({kinds}): A-labeled yes {ya0} -> {ya1}   U-labeled yes {yu0} -> {yu1}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
